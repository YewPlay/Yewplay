package org.schabi.newpipe.engine.model

// YewPlay MultiEngine — standardized internal models.
//
// Every extraction engine converts its own types into these models. Screens and
// services consume ONLY these types and never engine-specific classes, so the UI
// stays decoupled from NewPipeExtractor, MediaServiceCore and the FlowTube client.

/** One playable/downloadable stream format. */
data class YpMediaFormat(
    val url: String,
    val mimeType: String,
    /** e.g. "720p", "1080p" for video; bitrate label for audio. */
    val qualityLabel: String,
    val height: Int = 0,
    val fps: Int = 0,
    val bitrate: Int = 0,
    /** True for muxed audio+video; false for audio-only or video-only tracks. */
    val muxed: Boolean,
    val isAudioOnly: Boolean = false,
    val isVideoOnly: Boolean = false,
    /** True for DASH/HLS manifests rather than progressive files. */
    val isAdaptive: Boolean = false
)

data class YpSubtitleTrack(
    val url: String,
    val languageCode: String,
    val displayName: String,
    val isAutoGenerated: Boolean
)

/** Lightweight item used in search results, channels, playlists and feeds. */
data class YpMediaItem(
    val url: String,
    val title: String,
    val thumbnailUrl: String?,
    val authorName: String?,
    val authorUrl: String?,
    val durationSeconds: Long,
    val viewCount: Long,
    val uploadDate: String?,
    val isLive: Boolean = false
)

/** Full information for a single video/track, including playable formats. */
data class YpVideoInfo(
    val url: String,
    val title: String,
    val description: String,
    val thumbnailUrl: String?,
    val author: String,
    val authorUrl: String?,
    val durationSeconds: Long,
    val viewCount: Long,
    val uploadDate: String?,
    val formats: List<YpMediaFormat>,
    val subtitles: List<YpSubtitleTrack>,
    val likeCount: Long = -1,
    /** True for live broadcasts (ongoing or upcoming), false for regular VOD. */
    val isLive: Boolean = false
)

data class YpChannelInfo(
    val url: String,
    val name: String,
    val avatarUrl: String?,
    val description: String,
    val subscriberCount: Long,
    val items: List<YpMediaItem>,
    /** Opaque continuation key for [ExtractionEngine]-level pagination. */
    val nextPageKey: String?
)

data class YpPlaylistInfo(
    val url: String,
    val name: String,
    val thumbnailUrl: String?,
    val authorName: String?,
    val itemCount: Long,
    val items: List<YpMediaItem>,
    val nextPageKey: String?
)

/** One page of search results. [nextPageKey] is opaque and engine-specific. */
data class YpSearchPage(
    val items: List<YpMediaItem>,
    val channels: List<YpChannelItem>,
    val playlists: List<YpPlaylistItem>,
    val nextPageKey: String?
)

data class YpChannelItem(
    val url: String,
    val name: String,
    val avatarUrl: String?,
    val subscriberCount: Long,
    val description: String?
)

data class YpPlaylistItem(
    val url: String,
    val name: String,
    val thumbnailUrl: String?,
    val authorName: String?,
    val itemCount: Long
)
